const LOCALES = { en: 'en', fr: 'fr' };
let lang = 'en';
try {
  lang = localStorage.getItem('mic.lang') || (navigator.language || 'en').slice(0, 2);
} catch {
  /* stockage indisponible */
}
if (!LOCALES[lang]) lang = 'en';

export function getLang() {
  return lang;
}

export function setLang(next) {
  if (!LOCALES[next]) return;
  lang = next;
  document.documentElement.lang = next;
  try {
    localStorage.setItem('mic.lang', next);
  } catch {
    /* ignore */
  }
}
document.documentElement.lang = lang;

export function t(key, vars = {}) {
  const entry = DICT[key];
  let s = entry ? entry[lang === 'fr' ? 1 : 0] : key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

export function hasKey(key) {
  return key in DICT;
}

// Compteurs arrondis localisés : 1.2K / 1,2 k (16.7).
export function compact(n) {
  return new Intl.NumberFormat(lang, { notation: 'compact', maximumFractionDigits: 1 }).format(n);
}

export function relTime(ts) {
  const diff = (ts - Date.now()) / 1000;
  const abs = Math.abs(diff);
  if (abs < 45) return t('common.now');
  const rtf = new Intl.RelativeTimeFormat(lang, { numeric: 'auto', style: 'short' });
  if (abs < 3600) return rtf.format(Math.round(diff / 60), 'minute');
  if (abs < 86400) return rtf.format(Math.round(diff / 3600), 'hour');
  if (abs < 7 * 86400) return rtf.format(Math.round(diff / 86400), 'day');
  return new Intl.DateTimeFormat(lang, { day: 'numeric', month: 'short' }).format(ts);
}

export function clock(ts) {
  return new Intl.DateTimeFormat(lang, { hour: '2-digit', minute: '2-digit' }).format(ts);
}

export function dayLabel(ts) {
  const d = new Date(ts);
  const today = new Date();
  const y = new Date();
  y.setDate(today.getDate() - 1);
  if (d.toDateString() === today.toDateString()) return t('chat.today');
  if (d.toDateString() === y.toDateString()) return t('chat.yesterday');
  return new Intl.DateTimeFormat(lang, { weekday: 'long', day: 'numeric', month: 'long' }).format(d);
}

// Heure courte pour la liste des discussions.
export function listTime(ts) {
  const d = new Date(ts);
  if (d.toDateString() === new Date().toDateString()) return clock(ts);
  return new Intl.DateTimeFormat(lang, { day: 'numeric', month: 'short' }).format(d);
}
